//! The generator of `docs/errors.md` (AC-026).

use std::fmt::Write as _;

use super::{CodeInfo, DiagCode, ErrorCode, RepairClass, Reserved, WarningCode};

/// The text before the tables.
const INTRO: &str = "\
This file lists the frozen code catalogs of ghidorah (design Section 10.8, ADR-0002).
The test `ac_026_errors_doc_golden` makes this file from the enums of `ghidorah-base`.
Do not edit this file by hand. Run the test with `GHIDORAH_BLESS=1` to write it again.

Code numbers never change. No code uses a reserved number.
A message can hold placeholders such as `{field}`. The server fills them before output.
An error result takes the plain hint when the hint names a `next[0]` or candidates that the result does not hold.
";

/// The columns of a catalog table.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Columns {
    /// Num, code, class, retry, message, hint and plain hint.
    Error,
    /// Num, code, class, retry, message and hint.
    Warning,
    /// Num, code, message and hint.
    Diag,
}

/// Gives the body of `docs/errors.md`: the three catalogs as Markdown tables.
///
/// The golden header line comes before this body.
#[must_use]
pub fn errors_markdown() -> String {
    let mut out = String::from(INTRO);
    out.push_str("\n## Repair classes\n\n| Class | Meaning |\n|---|---|\n");
    for class in RepairClass::ALL {
        let _ = writeln!(out, "| {} | {} |", class.as_str(), class.meaning());
    }
    out.push_str(
        "\n## Error codes\n\n\
         A tool failure gives one error object with one of these codes.\n\n",
    );
    let errors: Vec<CodeInfo> = ErrorCode::ALL.iter().map(|c| c.info()).collect();
    write_table(&mut out, &errors, &ErrorCode::RESERVED, Columns::Error);
    out.push_str(
        "\n## Warning codes\n\n\
         A result warning has one of these codes. A remedy is a complete call.\n\n",
    );
    let warnings: Vec<CodeInfo> = WarningCode::ALL.iter().map(|c| c.info()).collect();
    write_table(
        &mut out,
        &warnings,
        &WarningCode::RESERVED,
        Columns::Warning,
    );
    out.push_str(
        "\n## Diagnostic codes\n\n\
         A loader diagnostic or a C parser error has one of these codes.\n\n",
    );
    let diags: Vec<CodeInfo> = DiagCode::ALL.iter().map(|c| c.info()).collect();
    write_table(&mut out, &diags, &[], Columns::Diag);
    out
}

/// Gives the header lines of a table with `columns`.
const fn header(columns: Columns) -> &'static str {
    match columns {
        Columns::Error => {
            "| Num | Code | Class | Retry | Message | Hint | Plain hint |\n|---|---|---|---|---|---|---|\n"
        }
        Columns::Warning => {
            "| Num | Code | Class | Retry | Message | Hint |\n|---|---|---|---|---|---|\n"
        }
        Columns::Diag => "| Num | Code | Message | Hint |\n|---|---|---|---|\n",
    }
}

/// Gives the table row of one code.
fn row(i: &CodeInfo, columns: Columns) -> String {
    let retry = if i.retry { "yes" } else { "no" };
    let (num, name, class) = (i.num, i.name, i.class.as_str());
    let (message, hint) = (i.message, i.hint);
    match columns {
        Columns::Error => format!(
            "| {num} | `{name}` | {class} | {retry} | {message} | {hint} | {} |",
            i.plain
        ),
        Columns::Warning => {
            format!("| {num} | `{name}` | {class} | {retry} | {message} | {hint} |")
        }
        Columns::Diag => format!("| {num} | `{name}` | {message} | {hint} |"),
    }
}

/// Writes one catalog table in number order. Reserved rows sit at their numbers.
fn write_table(out: &mut String, infos: &[CodeInfo], reserved: &[Reserved], columns: Columns) {
    out.push_str(header(columns));
    let mut rows: Vec<(u16, String)> = infos.iter().map(|i| (i.num, row(i, columns))).collect();
    let tail = if columns == Columns::Error {
        " - |"
    } else {
        ""
    };
    rows.extend(reserved.iter().map(|r| {
        (
            r.num,
            format!(
                "| {} | reserved | - | - | `{}` waits for stretch item {}. | - |{tail}",
                r.num, r.name, r.stretch
            ),
        )
    }));
    rows.sort();
    for (_, line) in rows {
        out.push_str(&line);
        out.push('\n');
    }
}
