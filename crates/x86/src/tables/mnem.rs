//! The canonical mnemonics (design Section 5.4).
//!
//! A mnemonic is lowercase, uses the Intel name and has no size suffix. The string
//! instructions are `movs`, `cmps`, `stos`, `lods`, `scas`, `ins` and `outs`.
//! `(vector)` marks an opaque form.

macro_rules! mnemonics {
    ($($variant:ident = $name:literal,)*) => {
        /// A canonical mnemonic.
        #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
        #[repr(u16)]
        pub enum Mnem {
            $(
                #[doc = concat!("`", $name, "`")]
                $variant,
            )*
        }

        /// The name of each mnemonic in declaration order.
        const NAMES: &[&str] = &[$($name,)*];

        impl Mnem {
            /// Every mnemonic in declaration order.
            pub const ALL: &[Self] = &[$(Self::$variant,)*];
        }
    };
}

impl Mnem {
    /// Gives the canonical name, for example `add` or `(vector)`.
    #[must_use]
    pub fn name(self) -> &'static str {
        NAMES.get(self as usize).copied().unwrap_or("?")
    }

    /// Finds the mnemonic of a canonical name.
    #[must_use]
    pub fn from_name(name: &str) -> Option<Self> {
        let i = NAMES.iter().position(|n| *n == name)?;
        Self::ALL.get(i).copied()
    }
}

impl std::fmt::Display for Mnem {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.name())
    }
}

